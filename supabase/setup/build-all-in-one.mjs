// Joins the migrations and the Street Heaven setup into one file that can be pasted
// into the Supabase SQL editor in one go:  node supabase/setup/build-all-in-one.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const parts = [
  "supabase/migrations/20261023000001_core_schema.sql",
  "supabase/migrations/20261023000002_pos_api.sql",
  "supabase/migrations/20261023000003_admin_api.sql",
  "supabase/migrations/20261024000004_device_login.sql",
  "supabase/migrations/20261030000005_service_and_photos.sql",
  "supabase/migrations/20261030000006_pay_later.sql",
  "supabase/migrations/20261031000007_sales_by_date.sql",
  "supabase/setup/street-heaven.sql",
];
const header = `-- ============================================================================
-- Street Heaven POS: complete database setup in ONE file.
-- Paste all of this into Supabase → SQL Editor → New query, then click Run. Run it ONCE
-- on a fresh project. (Generated by supabase/setup/build-all-in-one.mjs; don't edit by hand.)
-- After it succeeds, run the short "your details" query from the README.
-- ============================================================================
`;
const body = parts.map((p) => `\n-- ---------------------------------------------------------------- ${p}\n\n${readFileSync(join(root, p), "utf8")}`).join("\n");
writeFileSync(join(root, "supabase/setup/all-in-one.sql"), header + body);
console.log("wrote supabase/setup/all-in-one.sql");

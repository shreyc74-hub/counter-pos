// Generates SQL for the Street Heaven menu from the one source of truth:
// web/lib/data/menus/street-heaven.json (also used by the demo app).
//   node supabase/menus/generate.mjs
// Writes:
//   supabase/setup/street-heaven.sql   real outlet: menu + prices, costs left empty
//   supabase/seed.sql                  demo outlet: replaces the block between the MENU markers
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const menu = JSON.parse(readFileSync(join(root, "web/lib/data/menus/street-heaven.json"), "utf8"));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

function menuSql(id, outlet, withCosts, since) {
  const out = [];
  out.push("insert into public.categories (id, outlet_id, name, sort) values");
  out.push(menu.categories.map((c, i) => `  (${id(`cat-${c.key}`)}, ${outlet}, ${q(c.name)}, ${i + 1})`).join(",\n") + ";");
  out.push("", "insert into public.items (id, outlet_id, category_id, name, batch_cooked, sort) values");
  out.push(menu.items.map((it, i) => `  (${id(it.key)}, ${outlet}, ${id(`cat-${it.category}`)}, ${q(it.name)}, ${it.batchCooked}, ${i + 1})`).join(",\n") + ";");
  out.push("", "insert into public.variants (id, outlet_id, item_id, name, sort) values");
  out.push(menu.items.flatMap((it) => it.variants.map((v, i) => `  (${id(v.key)}, ${outlet}, ${id(it.key)}, ${q(v.name)}, ${i + 1})`)).join(",\n") + ";");
  out.push("", "insert into public.modifiers (id, outlet_id, name) values");
  out.push(menu.modifiers.map((m) => `  (${id(`mod-${m.key}`)}, ${outlet}, ${q(m.name)})`).join(",\n") + ";");
  const im = menu.items.flatMap((it) => it.modifiers.map((m, i) => `  (${id(it.key)}, ${id(`mod-${m}`)}, ${i + 1})`));
  if (im.length) out.push("", "insert into public.item_modifiers (item_id, modifier_id, sort) values", im.join(",\n") + ";");
  out.push("", "insert into public.price_history (outlet_id, ref_kind, ref_id, price_paise, cost_paise, effective_from) values");
  const rows = [
    ...menu.items.flatMap((it) =>
      it.variants.map((v) => `  (${outlet}, 'variant', ${id(v.key)}, ${v.price * 100}, ${withCosts && v.demoCost != null ? v.demoCost * 100 : "null"}, ${since})`),
    ),
    ...menu.modifiers.map((m) => `  (${outlet}, 'modifier', ${id(`mod-${m.key}`)}, ${m.price * 100}, ${withCosts ? 0 : "null"}, ${since})`),
  ];
  out.push(rows.join(",\n") + ";");
  if (menu.favourites.length) {
    out.push("", "insert into public.favourites (outlet_id, ref_id, sort) values");
    out.push(menu.favourites.map((k, i) => `  (${outlet}, ${id(k)}, ${i + 1})`).join(",\n") + ";");
  }
  return out.join("\n");
}

// ---- real outlet
const o = menu.outlet;
const real = `-- Street Heaven: the real outlet, with the full menu and prices. Costs are left empty:
-- enter them in the admin panel (Menu & prices). Run once in the Supabase SQL editor,
-- after the three migration files. Generated by supabase/menus/generate.mjs; don't edit by hand.

create or replace function pg_temp.sid(t text) returns uuid language sql immutable as $$ select md5('street-heaven:' || t)::uuid $$;

insert into public.outlets (id, name, address_line, phone, fssai_no, receipt_footer, is_demo)
values (pg_temp.sid('outlet'), ${q(o.name)}, ${q(o.addressLine)}, ${q(o.phone)}, ${q(o.fssaiNo)}, ${q(o.receiptFooter)}, false);

${menuSql((k) => `pg_temp.sid(${q(k)})`, "pg_temp.sid('outlet')", false, "now()")}

-- ---------------------------------------------------------------- your details (edit, then run)
-- 1. Link your email so you can sign in to /admin:
--      update public.outlets set owner_email = 'you@example.com', fssai_no = '<14-digit FSSAI>' where name = 'Street Heaven';
-- 2. Register the counter tablet. Choose a long random key; you type it into the tablet once:
--      insert into public.devices (outlet_id, code, name, token_hash)
--      select id, 'T1', 'Counter tablet', public._hash_key('<long random key>') from public.outlets where name = 'Street Heaven';
-- 3. Add staff with their own 4-digit PINs (one owner, then cashiers):
--      insert into public.staff (outlet_id, name, role, pin_hash)
--      select id, 'Shrey', 'owner', extensions.crypt('<PIN>', extensions.gen_salt('bf')) from public.outlets where name = 'Street Heaven';
`;
writeFileSync(join(root, "supabase/setup/street-heaven.sql"), real);

// ---- menu update for an outlet that is already live: switch to this menu without touching
// saved bills. Old sections/dishes are switched off (kept for history), the new ones added.
// Ids are prefixed with the menu name so they never clash with the ones already there.
const tag = menu.menuName ?? "menu";
const update = `-- Street Heaven: switch the LIVE outlet to the menu in web/lib/data/menus/street-heaven.json
-- ("${tag}"). Safe for saved bills: they keep their own copy of names and prices. Old menu
-- entries are switched off, not deleted. Run once in the Supabase SQL editor; running it
-- again does nothing. Generated by supabase/menus/generate.mjs; don't edit by hand.

create or replace function pg_temp.sid(t text) returns uuid language sql immutable as $$ select md5('street-heaven:${tag}:' || t)::uuid $$;
create or replace function pg_temp.oid() returns uuid language sql stable as $$ select id from public.outlets where name = ${q(o.name)} and not is_demo $$;

do $$
begin
  if pg_temp.oid() is null then raise exception 'No outlet named ${o.name}. Run street-heaven.sql first.'; end if;
  if exists (select 1 from public.categories where id = pg_temp.sid('cat-${menu.categories[0].key}')) then
    raise notice 'This menu is already loaded: nothing to do.';
    return;
  end if;
  update public.categories set active = false where outlet_id = pg_temp.oid();
  update public.items set active = false where outlet_id = pg_temp.oid();
  update public.variants set active = false where outlet_id = pg_temp.oid();
  update public.modifiers set active = false where outlet_id = pg_temp.oid();
  delete from public.favourites where outlet_id = pg_temp.oid();
  update public.outlets set menu_version = menu_version + 1 where id = pg_temp.oid();
  ${menuSql((k) => `pg_temp.sid(${q(k)})`, "pg_temp.oid()", false, "now()").replace(/\n/g, "\n  ")}
end $$;

select c.name as section, count(*) as dishes
from public.items i join public.categories c on c.id = i.category_id
where i.outlet_id = pg_temp.oid() and i.active group by c.name, c.sort order by c.sort;
`;
writeFileSync(join(root, `supabase/setup/street-heaven-${tag}.sql`), update);

// ---- demo seed: replace the generated menu block
const seedPath = join(root, "supabase/seed.sql");
const seed = readFileSync(seedPath, "utf8");
const start = "-- BEGIN MENU (generated by supabase/menus/generate.mjs)";
const end = "-- END MENU";
const a = seed.indexOf(start);
const b = seed.indexOf(end);
if (a < 0 || b < 0) throw new Error("MENU markers not found in seed.sql");
const block = `${start}\n${menuSql((k) => `pg_temp.id(${q(k)})`, "pg_temp.id('outlet')", true, "now() - interval '400 days'")}\n`;
writeFileSync(seedPath, seed.slice(0, a) + block + seed.slice(b));
console.log(`wrote supabase/setup/street-heaven.sql, street-heaven-${tag}.sql and the menu block in supabase/seed.sql`);
console.log("now run: node supabase/setup/build-all-in-one.mjs");
